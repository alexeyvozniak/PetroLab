from __future__ import annotations

import streamlit as st


def render_help_page() -> None:
    st.title("Инструкция")
    st.write("Короткий рабочий путь без необходимости помнить устройство базы.")

    st.markdown("### 1. Импорт анализов минералов")
    st.markdown(
        "1. Откройте **Источники и импорт** и выберите проект.\n"
        "2. Предпочтительно свяжите локальный XLSX/XLSM, если хотите двустороннюю синхронизацию.\n"
        "3. Для каждого листа проверьте минерал, заголовки, Sample/Grain/Point/Generation и предупреждения по Fe/единицам.\n"
        "4. Импортируйте. Порядок колонок не важен; исходные названия и позиции сохраняются для обратной записи."
    )

    st.markdown("### 2. Пересчёт и графики")
    st.markdown(
        "1. В **Расчёты и формулы** выберите метод и сохраните derived-результаты.\n"
        "2. В **XY**, **Треугольных** или **Научных диаграммах** используйте исходные и derived-поля вместе.\n"
        "3. Для публикации выберите журнальный preset, затем при необходимости измените шрифт, подписи, сетку и маркеры.\n"
        "4. Click/box/lasso служат для исследования точек; исключение из рисунка не удаляет анализ из базы."
    )

    st.markdown("### 3. REE, spider и статистика")
    st.markdown(
        "- **Научные диаграммы → REE / Spider** автоматически находят canonical trace-element колонки.\n"
        "- **Статистика и кластеры** позволяет считать описательную статистику, корреляции, PCA и K-means/иерархические кластеры.\n"
        "- Кластер можно сохранить как локальную рабочую группу и затем использовать на любом графике."
    )

    st.markdown("### 4. Породы")
    st.markdown(
        "1. Создайте породу или импортируйте таблицу валовых составов.\n"
        "2. Заполните паспорт: массив, литология, описание, возраст и методики.\n"
        "3. Добавьте химию, изотопию и общие фотографии.\n"
        "4. Свяжите минералогические dataset'ы, происходящие из этой породы.\n"
        "5. Используйте TAS, Harker/binary, REE/spider, isotope XY и mineral–rock/Rhodes."
    )

    st.markdown("### 5. Что ПетроЛаб принципиально не делает")
    st.markdown(
        "- Не угадывает неизвестную единицу trace element.\n"
        "- Не превращает compositional field в формальный IMA-вид без достаточных структурных данных.\n"
        "- Не удаляет исходные анализы при фильтрации выбросов.\n"
        "- Не записывает derived-поля обратно в исходный Excel как будто они были измерены.\n"
        "- Не рисует литературное поле, если его координаты не проверены."
    )
